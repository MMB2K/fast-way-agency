export type Language = keyof typeof translations;

// Les objets fr/en sont typés en littéral via `as const` (utile pour l'autocomplétion
// à l'écriture), mais leurs chaînes de caractères diffèrent d'une langue à l'autre.
// `Widen` généralise ces littéraux en `string` pour que `Translations` accepte
// indifféremment le bloc fr ou le bloc en.
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? readonly Widen<U>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

export type Translations = Widen<(typeof translations)["fr"]>;
